// 1반부터 6반까지의 평균 점수는 다음과 같다.
// 1반 : 85.6
// 2반 : 79.5
// 3반 : 83.1
// 4반 : 80.0
// 5반 : 78.2
// 6반 : 75.0
// 이 점수를 배열에 초기값으로 저장한 후, 두 반 번호를 입력받아 해당 반 평균 점수의 합을 출력하는 프로그램을 작성하시오.
// (출력은 소수 첫째 자리까지 출력한다.)
#include <stdio.h>

int main() {
    int num1, num2;
    float grade[6] = {85.6, 79.5, 83.1, 80.0, 78.2, 75.0};
    scanf("%d %d", &num1, &num2);
    printf("%.1f\n", grade[num1 - 1] + grade[num2 - 1]);
}


// 결과
// 입력 : 1 3
// 출력 : 168.7